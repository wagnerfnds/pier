// A person's prompt shows whatever it begins with; only the lines the
// agents write for themselves as the user's turn are skipped. The internal
// lines are the shapes Claude Code 2.1 and Codex write (synthetic text).
func TestOwnLine(t *testing.T) {
	for _, tc := range []struct {
		line string
		own  bool
	}{
		// The agents' own lines.
		{"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>", true},
		{"<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>opus</command-args>", true},
		{"<local-command-stdout>Set model to Opus</local-command-stdout>", true},
		{"<local-command-stderr>boom</local-command-stderr>", true},
		{"<bash-input>ls</bash-input>", true},
		{"<bash-stdout>README.md</bash-stdout><bash-stderr></bash-stderr>", true},
		{"<system-reminder>\nThe task tools haven't been used recently.\n</system-reminder>", true},
		{"<user-memory-input>Use pnpm</user-memory-input>", true},
		{"<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n</task-notification>", true},
		{"<fork-boilerplate>You are a fork.</fork-boilerplate>\n\nAudit the export reads.", true},
		{"<agent-message from=\"a1\">\nDone.\n</agent-message> trailing", true},
		{"<environment_context>\n  <cwd>/w/acme</cwd>\n</environment_context>", true},
		{"<codex_internal_context>x</codex_internal_context>", true},
		{"<skill>\n<name>deploy</name>\n</skill>", true},
		{"# AGENTS.md instructions for /w/acme\n\n<INSTRUCTIONS>\nUse pnpm.\n</INSTRUCTIONS>", true},
		{"# AGENTS.md instructions for /w/acme\n\n<INSTRUCTIONS>\nUse pnpm.\n</INSTRUCTIONS>\n<environment_context>x</environment_context>", true},
		// A tag added later, named as theirs are: blocks of it alone.
		{"<session-start-hook>ok</session-start-hook>", true},
		{"<new-note a=\"1\">x</new-note>\n\n<other_note>y</other_note>", true},
		{"<pasted_content id=\"a1\">\nlog\n</pasted_content id=\"a1\">", true},

		// People's prompts.
		{"<Button> não está alinhado", false},
		{"<div> isn't centered", false},
		{"<Foo/> crashes on mount", false},
		{"<div class=\"card\">Hi</div> has no padding", false},
		{"<p>Hello</p>", false},
		{"<my-button>Save</my-button> is misaligned", false},
		{"<router-link to=\"/x\">Home</router-link> doesn't navigate", false},
		{"<system-reminder> tags show in my log, why?", false},
		{"<- this arrow is wrong", false},
		{"< 5 items should hide the pager", false},
		{"<>", false},
		{"<<<<<<< HEAD left in app.ts", false},
		{"Caveat: the API returns 500 on retries", false},
		{"# AGENTS.md instructions are ignored, fix it", false},
		{"Fix the <Button>", false},
		{"", false},
	} {
		if got := ownLine(tc.line); got != tc.own {
			t.Errorf("ownLine(%q) = %v, want %v", tc.line, got, tc.own)
		}
	}
}

// typed is a prompt line as Claude Code 2.1 writes what the person typed:
// origin human, beside the prompt.
func typed(s string) m {
	u := user(s)
	u["origin"] = m{"kind": "human"}
	u["promptSource"] = "typed"
	return u
}

func TestPromptsThatBeginWithMarkupShow(t *testing.T) {
	res := readAll(t,
		user("<Button> não está alinhado"),
		assistant(m{"type": "text", "text": "Fixed the flex row."}),
		typed("<div> isn't centered"),
		assistant(m{"type": "text", "text": "Centered."}),
		queued("<Foo/> crashes", m{"kind": "human"}),
		user("<local-command-caveat>Caveat: ignore</local-command-caveat>"),
		user("<user-memory-input>Use pnpm</user-memory-input>"),
		user("Caveat: The messages below were generated by the user while running local commands. DO NOT respond."),
		typed("Caveat: retries double-charge"),
	)
	var got []string
	for _, it := range only(t, res.Items, "user") {
		s := it.Text
		if it.MidTurn {
			s += " (mid-turn)"
		}
		got = append(got, s)
	}
	want := []string{"<Button> não está alinhado", "<div> isn't centered", "<Foo/> crashes (mid-turn)", "Caveat: retries double-charge"}
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Fatalf("prompts %q, want %q", got, want)
	}
}

// Claude Code 2.1 marks every prompt line with origin human: those are the
// person's prompts, not mid-turn messages, and the same words typed again
// (after a reply, or after the same words were sent mid-turn) show again.
func TestTypedPromptsRepeat(t *testing.T) {
	res := readAll(t,
		typed("continue"),
		assistant(m{"type": "text", "text": "one"}),
		typed("continue"),
		assistant(m{"type": "text", "text": "two"}),
		queued("yes", m{"kind": "human"}),
		assistant(m{"type": "text", "text": "three"}),
		queued("yes", m{"kind": "human"}),
		assistant(m{"type": "text", "text": "four"}),
		typed("yes"),
		assistant(m{"type": "text", "text": "five"}),
	)
	var got []string
	for _, it := range res.Items {
		s := it.Kind + ":" + it.Text
		if it.MidTurn {
			s += "*"
		}
		got = append(got, s)
	}
	want := "user:continue|text:one|user:continue|text:two|user:yes*|text:three|user:yes*|text:four|user:yes|text:five"
	if strings.Join(got, "|") != want {
		t.Fatalf("got  %s\nwant %s", strings.Join(got, "|"), want)
	}
}

// Codex hands its model its context as the user's: those parts go, the
// person's words stay, whatever they begin with.
func TestCodexPromptsThatBeginWithMarkup(t *testing.T) {
	p := filepath.Join(t.TempDir(), "rollout.jsonl")
	msg := func(parts ...string) m {
		var content []m
		for _, s := range parts {
			content = append(content, m{"type": "input_text", "text": s})
		}
		return m{"type": "response_item", "timestamp": "2026-10-04T12:00:00Z", "payload": m{"type": "message", "role": "user", "content": content}}
	}
	write(t, p,
		msg("# AGENTS.md instructions for /w/acme\n\n<INSTRUCTIONS>\nUse pnpm.\n</INSTRUCTIONS>", "<environment_context>\n  <cwd>/w/acme</cwd>\n</environment_context>"),
		msg("<Button> is misaligned"),
		msg("<environment_context>x</environment_context>", "<div> isn't centered"),
	)
	res, err := NewReader().Read("codex", p, "/w/acme", 0)
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Join(prompts(res.Items), "|"); got != "<Button> is misaligned|<div> isn't centered" {
		t.Fatalf("prompts %q", got)
	}
}

// A prompt is kept to 4000 bytes: cut at the last whole character within
// them, then "…" (3 bytes), so at most 4003 bytes. Characters are code
// points: a flag or an emoji sequence can lose its second half.
func TestUserTextClipsAt4000Bytes(t *testing.T) {
	for _, tc := range []struct {
		name, in, want string
	}{
		{"fits", strings.Repeat("a", 4000), strings.Repeat("a", 4000)},
		{"ascii", strings.Repeat("a", 4001), strings.Repeat("a", 4000) + "…"},
		{"a 2-byte letter across the limit", strings.Repeat("a", 3999) + "é!", strings.Repeat("a", 3999) + "…"},
		{"a 4-byte emoji across the limit", strings.Repeat("a", 3998) + "😀!", strings.Repeat("a", 3998) + "…"},
		{"a flag split between its halves", strings.Repeat("a", 3996) + "🇧🇷!", strings.Repeat("a", 3996) + "🇧…"},
		{"CJK", strings.Repeat("語", 1400), strings.Repeat("語", 1333) + "…"},
	} {
		res := readAll(t, user(tc.in))
		if len(res.Items) != 1 || res.Items[0].Text != tc.want {
			t.Errorf("%s: got %d bytes, want %d", tc.name, len(res.Items[0].Text), len(tc.want))
		}
	}
}

// A step's command reads as its first line, a Windows line end or not.
func TestFirstLine(t *testing.T) {
	for in, want := range map[string]string{
		"pnpm test":              "pnpm test",
		"pnpm test\necho done":   "pnpm test …",
		"pnpm test\r\necho done": "pnpm test …",
		"  echo 日本語 😀\n\nexit 1": "echo 日本語 😀 …",
	} {
		if got := firstLine(in); got != want {
			t.Errorf("firstLine(%q) = %q, want %q", in, got, want)
		}
	}
}
